# 智能路由：根据查询自动选择引擎
# ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

def detect_tour_type(query: str) -> str:
    """
    智能检测查询类型
    
    Returns:
        'weekend' - 周末游
        'history' - 历史人文游
        'general' - 通用（降级为旧版Prompt）
    """
    # 周末游关键词
    weekend_keywords = [
        '周末', '周六', '周日', '两天', '2天', '48小时',
        '带娃', '亲子', '孩子', '小朋友',
        '附近', '周边', '郊游', '短途'
    ]
    
    # 历史人文游关键词
    history_keywords = [
        '历史', '文化', '古迹', '遗址', '博物馆',
        '深度', '人文', '故事', '传统',
        '古城', '古镇', '古村', '古建筑',
        '寺庙', '道观', '书院', '祠堂'
    ]
    
    query_lower = query.lower()
    
    # 计算匹配分数
    weekend_score = sum(1 for kw in weekend_keywords if kw in query_lower)
    history_score = sum(1 for kw in history_keywords if kw in query_lower)
    
    if weekend_score > history_score and weekend_score >= 1:
        return 'weekend'
    elif history_score > weekend_score and history_score >= 1:
        return 'history'
    else:
        return 'general'


def build_prompt(query: str, mode: str = 'auto') -> dict:
    """
    智能构建Prompt
    
    Args:
        query: 用户查询
        mode: 'auto' / 'weekend' / 'history' / 'general'
    
    Returns:
        {
            'type': 'weekend' | 'history' | 'general',
            'prompt': str,
            'system_prompt': str
        }
    """
    if mode == 'auto':
        tour_type = detect_tour_type(query)
    else:
        tour_type = mode
    
    if tour_type == 'weekend':
        return {
            'type': 'weekend',
            'system_prompt': WEEKEND_TOUR_SYSTEM_PROMPT,
            'prompt': WEEKEND_TOUR_PROMPT.format(query=query)
        }
    elif tour_type == 'history':
        return {
            'type': 'history',
            'system_prompt': HISTORY_CULTURE_SYSTEM_PROMPT,
            'prompt': HISTORY_CULTURE_PROMPT.format(query=query)
        }
    else:
        # 降级为通用Prompt（保留旧版）
        from backend.prompts.wildtrip_prompt import build_wildtrip_prompt
        return {
            'type': 'general',
            'system_prompt': '',
            'prompt': build_wildtrip_prompt(query, mode='full')
        }


