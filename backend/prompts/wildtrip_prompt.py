def build_wildtrip_prompt(query: str, mode: str = "full", real_poi_data: str = "") -> str:
    """
    构建野游记Prompt
    
    Args:
        query: 用户查询
        mode: 模式
            - "full": 完整攻略（行程+酒店+餐饮+门票）
            - "hotel": 只推荐酒店
            - "food": 只推荐美食
        real_poi_data: 真实POI数据（格式化后的文本）
            
    Returns:
        完整prompt
    """
    if mode == "hotel":
        # 提取城市名称
        city_name = extract_city_name(query)
        return WILDTRIP_SYSTEM_PROMPT + "\n\n" + WILDTRIP_HOTEL_ONLY_PROMPT.format(
            query=query,
            city_name=city_name,
            landmark="市中心"  # 可后期优化为真实地标
        )
    elif mode == "food":
        city_name = extract_city_name(query)
        return WILDTRIP_SYSTEM_PROMPT + "\n\n" + WILDTRIP_FOOD_ONLY_PROMPT.format(
            query=query,
            city_name=city_name
        )
    else:
        # 完整攻略 - 🔥 添加时间戳增加随机性
        import time
        from datetime import datetime
        timestamp = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
        randomness_hint = f"\n\n🎲 生成时间: {timestamp}\n💡 请生成与之前不同的推荐内容，避免千篇一律"
        
        # 如果没有真实POI数据，给个提示
        if not real_poi_data:
            real_poi_data = "（暂无真实POI数据，请根据常识推荐，但尽量真实具体）"
        
        return WILDTRIP_SYSTEM_PROMPT + "\n\n" + WILDTRIP_TRAVEL_PLAN_PROMPT.format(
            query=query,
            real_poi_data=real_poi_data
        ) + randomness_hint


def extract_city_name(query: str) -> str:
    """
    从查询中提取城市名称（简单版本）
    
    TODO: 后期可用NER或LLM提取
    """
    # 常见城市列表（简化版）
    cities = [
        "海口", "三亚", "成都", "重庆", "西安", "北京", "上海", "杭州",
        "南京", "苏州", "广州", "深圳", "厦门", "青岛", "大连", "长沙"
    ]
    
    for city in cities:
        if city in query:
            return city
    
    return "目的地"


