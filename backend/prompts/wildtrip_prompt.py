def build_wildtrip_prompt(query: str, mode: str = "full") -> str:
    """
    构建野游记Prompt

    Args:
        query: 用户查询
        mode: 模式
            - "full": 完整攻略（行程+酒店+餐饮+门票）
            - "hotel": 只推荐酒店
            - "food": 只推荐美食

    Returns:
        完整prompt
    """
    if mode == "hotel":
        city_name = extract_city_name(query)
        return WILDTRIP_SYSTEM_PROMPT + "\n\n" + WILDTRIP_HOTEL_ONLY_PROMPT.format(
            query=query,
            city_name=city_name,
        )
    elif mode == "food":
        city_name = extract_city_name(query)
        return WILDTRIP_SYSTEM_PROMPT + "\n\n" + WILDTRIP_FOOD_ONLY_PROMPT.format(
            query=query,
            city_name=city_name
        )
    else:
        # 完整攻略 - 添加时间戳增加随机性
        from datetime import datetime
        timestamp = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
        randomness_hint = f"\n\n生成时间: {timestamp}\n请生成与之前不同的推荐内容，覆盖不同的餐厅和酒店。"

        return WILDTRIP_SYSTEM_PROMPT + "\n\n" + WILDTRIP_TRAVEL_PLAN_PROMPT.format(
            query=query
        ) + randomness_hint


def extract_city_name(query: str) -> str:
    """
    从查询中提取城市名称（简单版本）
    """
    cities = [
        "海口", "三亚", "成都", "重庆", "西安", "北京", "上海", "杭州",
        "南京", "苏州", "广州", "深圳", "厦门", "青岛", "大连", "长沙",
        "昆明", "大理", "丽江", "桂林", "武汉", "郑州", "天津", "哈尔滨",
        "沈阳", "贵阳", "拉萨", "兰州", "银川", "西宁", "呼和浩特",
        "福州", "南昌", "合肥", "济南", "太原", "石家庄", "乌鲁木齐",
        "珠海", "中山", "东莞", "佛山", "惠州", "汕头", "潮州"
    ]

    for city in cities:
        if city in query:
            return city

    return "目的地"


